"""Production PostgreSQL store with the same contract as local SQLite storage.

This module is imported only when DATABASE_URL is set. A Supabase connection
URI may be used; include sslmode=require. Schema creation is a separate,
privileged one-time operation; collection uses a DML-only role.
"""

from __future__ import annotations

from .models import Market, Signal


SCHEMA = """
CREATE TABLE IF NOT EXISTS markets (
  market_id TEXT PRIMARY KEY,
  event_id TEXT NOT NULL,
  event_title TEXT NOT NULL,
  event_slug TEXT NOT NULL,
  question TEXT NOT NULL,
  yes_token_id TEXT NOT NULL,
  end_date TEXT NOT NULL,
  last_seen_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS snapshots (
  market_id TEXT NOT NULL REFERENCES markets(market_id),
  observed_at BIGINT NOT NULL,
  yes_price DOUBLE PRECISION NOT NULL CHECK (yes_price BETWEEN 0 AND 1),
  volume_24h DOUBLE PRECISION NOT NULL CHECK (volume_24h >= 0),
  liquidity DOUBLE PRECISION NOT NULL CHECK (liquidity >= 0),
  price_basis TEXT NOT NULL DEFAULT 'gamma_outcomePrices',
  PRIMARY KEY(market_id, observed_at)
);
CREATE INDEX IF NOT EXISTS idx_snapshots_time ON snapshots(observed_at);
CREATE TABLE IF NOT EXISTS signals (
  signal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market_id TEXT NOT NULL REFERENCES markets(market_id),
  observed_at BIGINT NOT NULL,
  baseline_at BIGINT NOT NULL,
  window_hours INTEGER NOT NULL,
  previous_price DOUBLE PRECISION NOT NULL,
  current_price DOUBLE PRECISION NOT NULL,
  change_pp DOUBLE PRECISION NOT NULL,
  score INTEGER NOT NULL,
  volume_24h DOUBLE PRECISION NOT NULL,
  liquidity DOUBLE PRECISION NOT NULL,
  UNIQUE(market_id,observed_at)
);
CREATE INDEX IF NOT EXISTS idx_signals_time ON signals(observed_at DESC);
CREATE INDEX IF NOT EXISTS idx_signals_market_time ON signals(market_id,observed_at DESC);
CREATE TABLE IF NOT EXISTS runs (
  run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at BIGINT NOT NULL,
  finished_at BIGINT,
  status TEXT NOT NULL,
  source TEXT NOT NULL,
  events_scanned INTEGER NOT NULL DEFAULT 0,
  markets_saved INTEGER NOT NULL DEFAULT 0,
  signals_created INTEGER NOT NULL DEFAULT 0,
  error_message TEXT
);
CREATE INDEX IF NOT EXISTS idx_runs_start ON runs(started_at DESC);
CREATE TABLE IF NOT EXISTS metadata (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
ALTER TABLE markets ENABLE ROW LEVEL SECURITY;
ALTER TABLE snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE signals ENABLE ROW LEVEL SECURITY;
ALTER TABLE runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE metadata ENABLE ROW LEVEL SECURITY;
"""


class PostgresStorage:
    """Production implementation of the methods used by the pipeline.

    Uses an autocommit connection and explicit transactions for each complete
    snapshot batch.  A process crash cannot leave partial batch ingestion.
    """

    def __init__(self, url: str, *, initialize: bool = False):
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError("Production requires pip install '.[postgres]'") from exc
        try:
            self.db = psycopg.connect(url, autocommit=True, row_factory=dict_row,
                                      connect_timeout=10, prepare_threshold=None)
            if initialize:
                self.initialize_schema()
        except Exception as exc:
            # Psycopg diagnostics can contain connection details. Do not leak
            # database URIs or passwords to shared job logs or tracebacks.
            raise RuntimeError(f"PostgreSQL connection/setup failed ({type(exc).__name__})") from None

    def initialize_schema(self) -> None:
        """Run once with a privileged migration credential, never in a job."""
        with self.db.transaction():
            for statement in SCHEMA.split(";"):
                if statement.strip():
                    self.db.execute(statement)

    def __enter__(self) -> "PostgresStorage":
        return self

    def __exit__(self, *_: object) -> None:
        self.db.close()

    @staticmethod
    def bucket(timestamp: int, interval_seconds: int = 900) -> int:
        return timestamp - timestamp % interval_seconds

    def save_snapshots(self, markets: list[Market], observed_at: int) -> int:
        bucket = self.bucket(observed_at)
        inserted = 0
        with self.db.transaction():
            for market in markets:
                self.db.execute(
                    """INSERT INTO markets
                    (market_id,event_id,event_title,event_slug,question,yes_token_id,end_date,last_seen_at)
                    VALUES (%s,%s,%s,%s,%s,%s,%s,%s)
                    ON CONFLICT(market_id) DO UPDATE SET
                    event_title=excluded.event_title, event_slug=excluded.event_slug,
                    question=excluded.question, end_date=excluded.end_date,
                    last_seen_at=excluded.last_seen_at""",
                    (market.market_id, market.event_id, market.event_title, market.event_slug,
                     market.question, market.yes_token_id, market.end_date, bucket),
                )
                row = self.db.execute(
                    """INSERT INTO snapshots
                    (market_id,observed_at,yes_price,volume_24h,liquidity)
                    VALUES (%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING RETURNING market_id""",
                    (market.market_id, bucket, market.yes_price,
                     market.volume_24h, market.liquidity),
                ).fetchone()
                inserted += int(row is not None)
        return inserted

    def reference_snapshot(self, market_id: str, target_time: int, tolerance: int) -> tuple[int, float] | None:
        row = self.db.execute(
            """SELECT observed_at,yes_price FROM snapshots
            WHERE market_id=%s AND observed_at BETWEEN %s AND %s
            ORDER BY ABS(observed_at - %s) ASC LIMIT 1""",
            (market_id, target_time - tolerance, target_time + tolerance, target_time),
        ).fetchone()
        return (int(row["observed_at"]), float(row["yes_price"])) if row else None

    def recent_signal_exists(self, market_id: str, observed_at: int, cooldown_seconds: int = 21600) -> bool:
        row = self.db.execute(
            "SELECT 1 FROM signals WHERE market_id=%s AND observed_at>%s LIMIT 1",
            (market_id, observed_at - cooldown_seconds),
        ).fetchone()
        return row is not None

    def save_signal(self, signal: Signal) -> bool:
        row = self.db.execute(
            """INSERT INTO signals
            (market_id,observed_at,baseline_at,window_hours,previous_price,current_price,change_pp,score,volume_24h,liquidity)
            VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING
            RETURNING signal_id""",
            (signal.market_id, signal.observed_at, signal.baseline_at, signal.window_hours,
             signal.previous_price, signal.current_price, signal.change_pp, signal.score,
             signal.volume_24h, signal.liquidity),
        ).fetchone()
        return row is not None

    def start_run(self, started_at: int, source: str = "live") -> int:
        row = self.db.execute(
            "INSERT INTO runs (started_at,status,source) VALUES (%s,%s,%s) RETURNING run_id",
            (started_at, "running", source),
        ).fetchone()
        return int(row["run_id"])

    def finish_run(self, run_id: int, finished_at: int, *, status: str,
                   events: int = 0, markets: int = 0, signals: int = 0,
                   error: str | None = None) -> None:
        self.db.execute(
            """UPDATE runs SET finished_at=%s,status=%s,events_scanned=%s,
            markets_saved=%s,signals_created=%s,error_message=%s WHERE run_id=%s""",
            (finished_at, status, events, markets, signals, error, run_id),
        )

    def recover_stale_runs(self, now: int, stale_after: int = 1800) -> int:
        row = self.db.execute(
            """UPDATE runs SET status='interrupted',finished_at=%s,
            error_message='Worker terminated without completing run'
            WHERE status='running' AND started_at<%s RETURNING run_id""",
            (now, now - stale_after),
        ).fetchall()
        return len(row)

    def set_metadata(self, key: str, value: str) -> None:
        self.db.execute(
            "INSERT INTO metadata VALUES (%s,%s) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (key, value),
        )

    def get_metadata(self, key: str, default: str = "") -> str:
        row = self.db.execute("SELECT value FROM metadata WHERE key=%s", (key,)).fetchone()
        return str(row["value"]) if row else default

    def dashboard_data(self, limit: int = 30) -> dict:
        signals = self.db.execute(
            """SELECT s.*,m.question,m.event_title,m.event_slug FROM signals s
            JOIN markets m USING(market_id) ORDER BY s.observed_at DESC,s.score DESC LIMIT %s""",
            (limit,),
        ).fetchall()
        markets = self.db.execute(
            """SELECT m.*,s.yes_price,s.volume_24h,s.liquidity,s.observed_at
            FROM markets m JOIN LATERAL
            (SELECT * FROM snapshots WHERE market_id=m.market_id
             ORDER BY observed_at DESC LIMIT 1) s ON TRUE
            ORDER BY s.volume_24h DESC LIMIT %s""",
            (limit,),
        ).fetchall()
        runs = self.db.execute("SELECT * FROM runs ORDER BY run_id DESC LIMIT 8").fetchall()
        stats = self.db.execute(
            """SELECT (SELECT COUNT(*) FROM markets) markets,
            (SELECT COUNT(*) FROM snapshots) observations,
            (SELECT COUNT(*) FROM signals) signals,
            (SELECT COUNT(*) FROM runs WHERE status IN ('error','interrupted')) failures"""
        ).fetchone()
        return {"stats": dict(stats), "signals": list(signals), "markets": list(markets),
                "runs": list(runs), "dataset": self.get_metadata("dataset", "live")}

    def prune_snapshots(self, cutoff: int) -> int:
        """Expire old routine quotes while retaining signal provenance points."""
        row = self.db.execute(
            """DELETE FROM snapshots p WHERE p.observed_at < %s
            AND NOT EXISTS (
              SELECT 1 FROM signals s WHERE s.market_id=p.market_id
              AND (s.observed_at=p.observed_at OR s.baseline_at=p.observed_at)
            ) RETURNING market_id""",
            (cutoff,),
        ).fetchall()
        return len(row)


def open_storage(db_file: str):
    """Choose durable hosted storage when configured, local SQLite otherwise.

    Cloud jobs set REQUIRE_PERSISTENT_DB=1 to prevent accidental operation with
    an ephemeral file if the secret is missing.
    """
    import os
    url = os.environ.get("DATABASE_URL")
    if url:
        return PostgresStorage(url)
    if os.environ.get("REQUIRE_PERSISTENT_DB") == "1":
        raise RuntimeError("Refusing ephemeral SQLite: DATABASE_URL is missing")
    from .storage import Storage
    return Storage(db_file)
